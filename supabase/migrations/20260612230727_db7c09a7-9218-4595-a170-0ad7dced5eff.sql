-- Finance entries table
CREATE TABLE public.finance_entries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  month text NOT NULL,
  section text NOT NULL CHECK (section IN ('income','subscription','fixed','daily','food')),
  category text,
  name text NOT NULL,
  planned numeric NOT NULL DEFAULT 0,
  actual numeric NOT NULL DEFAULT 0,
  due_day text,
  note text,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX finance_entries_month_section_idx ON public.finance_entries(month, section);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.finance_entries TO authenticated;
GRANT ALL ON public.finance_entries TO service_role;

ALTER TABLE public.finance_entries ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Approved users can view finance" ON public.finance_entries
  FOR SELECT TO authenticated USING (public.is_approved(auth.uid()));
CREATE POLICY "Approved users can insert finance" ON public.finance_entries
  FOR INSERT TO authenticated WITH CHECK (public.is_approved(auth.uid()));
CREATE POLICY "Approved users can update finance" ON public.finance_entries
  FOR UPDATE TO authenticated USING (public.is_approved(auth.uid()));
CREATE POLICY "Approved users can delete finance" ON public.finance_entries
  FOR DELETE TO authenticated USING (public.is_approved(auth.uid()));

CREATE TRIGGER finance_entries_updated_at
  BEFORE UPDATE ON public.finance_entries
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

